export const messages: Record<Locale, Record<TranslationKey, string>> = { fr, en };

export function translate(
  locale: Locale,
  key: TranslationKey,
  vars?: Record<string, string | number>,
) {
  const template = messages[locale][key] ?? messages.en[key] ?? String(key);
  if (!vars) {
    return template;
  }
  return template.replace(/\{(\w+)\}/g, (_, name: string) =>
    String(vars[name] ?? `{${name}}`),
  );
}

const ACTION_KEYS: Record<string, TranslationKey> = {
  auto: "action.auto",
  email: "action.email",
  report: "action.report",
  both: "action.both",
  unsupported: "action.unsupported",
  unknown: "action.unsupported",
};

export function actionLabel(locale: Locale, action: string) {
  return translate(locale, ACTION_KEYS[action] ?? "action.unsupported");
}

export function statusLabel(locale: Locale, message: string) {
  if (message.trim().toLowerCase() === "routing request") {
    return translate(locale, "status.routing");
  }
  return message;
}
